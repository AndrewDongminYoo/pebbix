"""Keep generated local options and the iOS symbol-upload phase compatible with project gates."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OPTIONS = ROOT / "lib/firebase_options.dart"
PROJECT = ROOT / "ios/Runner.xcodeproj/project.pbxproj"
PHASE = 'FlutterFire: \\"flutterfire upload-crashlytics-symbols\\"'


def update_options() -> None:
    source = OPTIONS.read_text()
    if not source.startswith("// File generated by FlutterFire CLI.\n"):
        raise ValueError("Unexpected FlutterFire options header")
    marker = "// coverage:ignore-file\n"
    if marker not in source:
        source = source.replace(
            "// File generated by FlutterFire CLI.\n",
            "// File generated by FlutterFire CLI.\n" + marker,
            1,
        )
        OPTIONS.write_text(source)


def update_project() -> None:
    source = PROJECT.read_text()
    matches = list(
        re.finditer(
            r"\t\t[0-9A-F]{24} /\* FlutterFire: .*? \*/ = \{.*?\n\t\t\};",
            source,
            re.DOTALL,
        )
    )
    phases = [match for match in matches if PHASE in match.group()]
    if len(phases) != 1:
        raise ValueError(
            f"Expected one FlutterFire Crashlytics phase, found {len(phases)}"
        )
    phase = phases[0].group()
    input_paths = (
        "${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}",
        "${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}/Contents/Resources/DWARF/${PRODUCT_NAME}",
        "${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}/Contents/Info.plist",
        "$(TARGET_BUILD_DIR)/$(UNLOCALIZED_RESOURCES_FOLDER_PATH)/GoogleService-Info.plist",
        "$(TARGET_BUILD_DIR)/$(EXECUTABLE_PATH)",
    )
    input_lines = "\n".join(f"\t\t\t{json.dumps(item)}," for item in input_paths)
    phase, count = re.subn(
        r"\t\t\tinputPaths = \(\n.*?\t\t\t\);",
        f"\t\t\tinputPaths = (\n{input_lines}\n\t\t\t);",
        phase,
        count=1,
        flags=re.DOTALL,
    )
    if count != 1:
        raise ValueError("Unexpected Crashlytics input paths")
    script = '''set -eu
case "$CONFIGURATION" in Release-production) ;; *) exit 0 ;; esac
script="$BUILD_DIR/SourcePackages/checkouts/firebase-ios-sdk/Crashlytics/run"
if [ ! -f "$script" ]; then
  script="${BUILD_DIR%/Build/*}/SourcePackages/checkouts/firebase-ios-sdk/Crashlytics/run"
fi
if [ ! -f "$script" ]; then
  script="$PROJECT_DIR/../$FLUTTER_BUILD_DIR/ios/SourcePackages/checkouts/firebase-ios-sdk/Crashlytics/run"
fi
if [ ! -f "$script" ]; then
  echo "Firebase Crashlytics SPM upload script is missing" >&2
  exit 1
fi
"$script"'''
    phase, count = re.subn(
        r"\t\t\tshellScript = .*?;\n",
        lambda _: "\t\t\tshellScript = " + json.dumps(script) + ";\n",
        phase,
        count=1,
    )
    if count != 1:
        raise ValueError("Unexpected Crashlytics shell script")
    PROJECT.write_text(source[: phases[0].start()] + phase + source[phases[0].end() :])


if __name__ == "__main__":
    update_options()
    update_project()
